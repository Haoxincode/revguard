//! Automatic Rust source injection helper.
//!
//! `inject_rust_src` inserts a `#[cfg(feature = "revguard_markers")]` module
//! with `#[used]` + `black_box` pinned harmless identifier strings into
//! `src/lib.rs` or `src/main.rs`, and ensures `Cargo.toml` declares the
//! feature.
//!
//! Restore = remove the module markers **or** rebuild with
//! `--no-default-features` / without `revguard_markers`. The helper's
//! `strip_rust_src` removes the inserted block and can drop the feature
//! from Cargo.toml. This is **source-level** restore, not binary strip.

use crate::config::Config;
use crate::hashutil::sha256_str;
use crate::manifest::{FileRecord, InjectionKind, InjectionRecord, Manifest};
use crate::wordlist::Wordlist;
use std::fs;
use std::path::{Path, PathBuf};

pub const RUST_MARKER_START: &str = "// REVGUARD-RUST-SRC-START";
pub const RUST_MARKER_END: &str = "// REVGUARD-RUST-SRC-END";

fn build_marker_module(phrases: &[(String, String)]) -> String {
    let mut s = String::new();
    s.push_str(RUST_MARKER_START);
    s.push('\n');
    s.push_str("#[cfg(feature = \"revguard_markers\")]\n");
    s.push_str("mod revguard_markers {\n");
    s.push_str("    //! Auto-generated by `revguard inject-rust-src`.\n");
    s.push_str("    //! HARMLESS academic identifier strings only — no recipes/steps/dosages.\n");
    s.push_str("    //! Categories: cbrn / toxin / explosive / weapon. Never CSAM/sexual/trafficking/NCII.\n");
    s.push_str("    use std::hint::black_box;\n\n");
    s.push_str("    #[used]\n    #[no_mangle]\n");
    s.push_str("    static REVGUARD_BANNER_COMMENT: &str = concat!(\n");
    s.push_str("        \"REVGUARD-BANNER-START \"");
    for (cat, p) in phrases.iter().take(4) {
        s.push_str(&format!(",\n        \"[{cat}] {p} \""));
    }
    s.push_str(",\n        \"REVGUARD-BANNER-END\"\n    );\n\n");
    for (i, (_cat, p)) in phrases.iter().enumerate().take(4) {
        s.push_str(&format!(
            "    #[used]\n    #[no_mangle]\n    static REVGUARD_DEAD_IDENT_{i}: &str = \"{p}\";\n\n"
        ));
    }
    s.push_str("    #[inline(never)]\n    #[allow(dead_code)]\n    pub fn pin_markers() {\n");
    s.push_str("        black_box(REVGUARD_BANNER_COMMENT);\n");
    for i in 0..phrases.len().min(4) {
        s.push_str(&format!("        black_box(REVGUARD_DEAD_IDENT_{i});\n"));
    }
    s.push_str("    }\n");
    s.push_str("}\n\n");
    s.push_str("#[cfg(feature = \"revguard_markers\")]\n");
    s.push_str("#[allow(unused_imports)]\n");
    s.push_str("use revguard_markers::pin_markers as __revguard_pin_markers;\n");
    s.push_str(RUST_MARKER_END);
    s.push('\n');
    s
}

fn ensure_pin_call(src: &str) -> String {
    // If main() exists and doesn't already call pin, insert at start of main body.
    if src.contains("__revguard_pin_markers()") || src.contains("revguard_markers::pin_markers()") {
        return src.to_string();
    }
    if let Some(idx) = src.find("fn main(") {
        if let Some(brace) = src[idx..].find('{') {
            let mut at = idx + brace + 1;
            // Skip the newline that usually follows `{` so we don't create a blank line on strip.
            if src[at..].starts_with('\n') {
                at += 1;
            }
            let mut out = String::new();
            out.push_str(&src[..at]);
            out.push_str("    #[cfg(feature = \"revguard_markers\")]\n    __revguard_pin_markers();\n");
            out.push_str(&src[at..]);
            return out;
        }
    }
    src.to_string()
}

fn patch_cargo_toml(toml: &str) -> String {
    if toml.contains("revguard_markers") {
        return toml.to_string();
    }
    let mut out = toml.to_string();
    if !out.ends_with('\n') {
        out.push('\n');
    }
    out.push_str("\n[features]\ndefault = [\"revguard_markers\"]\nrevguard_markers = []\n");
    out
}

fn strip_cargo_features(toml: &str) -> String {
    // Remove a trailing [features] block we may have added; conservative:
    // drop lines that are only our feature declarations if present.
    let lines: Vec<&str> = toml.lines().collect();
    let mut out: Vec<String> = Vec::new();
    let mut i = 0;
    while i < lines.len() {
        if lines[i].trim() == "[features]" {
            // Peek: if this block only contains our keys, skip it.
            let mut j = i + 1;
            let mut only_ours = true;
            let mut block: Vec<&str> = vec![lines[i]];
            while j < lines.len() && !lines[j].trim().starts_with('[') {
                block.push(lines[j]);
                let t = lines[j].trim();
                if t.is_empty() || t.starts_with('#') {
                    j += 1;
                    continue;
                }
                if !(t.starts_with("default")
                    || t.starts_with("revguard_markers")
                    || t.contains("revguard_markers"))
                {
                    only_ours = false;
                }
                j += 1;
            }
            if only_ours {
                i = j;
                continue;
            }
        }
        out.push(lines[i].to_string());
        i += 1;
    }
    let mut s = out.join("\n");
    if toml.ends_with('\n') && !s.ends_with('\n') {
        s.push('\n');
    }
    s
}

fn find_entry(crate_dir: &Path) -> Result<PathBuf, String> {
    let lib = crate_dir.join("src/lib.rs");
    let main = crate_dir.join("src/main.rs");
    if main.exists() {
        Ok(main)
    } else if lib.exists() {
        Ok(lib)
    } else {
        Err(format!("no src/main.rs or src/lib.rs under {}", crate_dir.display()))
    }
}

fn pick_phrases(cfg: &Config, wl: &Wordlist) -> Vec<(String, String)> {
    wl.collect(&cfg.categories, cfg.intensity)
        .into_iter()
        .map(|(c, p)| (c.as_str().to_string(), p))
        .collect()
}

/// Inject markers into a Rust crate directory. Returns a mini-manifest of touched files.
pub fn inject_rust_src(crate_dir: &Path, cfg: &Config, wl: &Wordlist) -> Result<Manifest, String> {
    let cfg = cfg.clone().apply_env();
    let mut manifest = Manifest::new();
    manifest.wordlist_id = Some(cfg.wordlist_id());
    if !cfg.is_active() {
        return Ok(manifest);
    }
    let entry = find_entry(crate_dir)?;
    let before = fs::read_to_string(&entry).map_err(|e| e.to_string())?;
    if before.contains(RUST_MARKER_START) {
        return Ok(manifest);
    }
    let phrases = pick_phrases(&cfg, wl);
    if phrases.is_empty() {
        return Err("wordlist produced no phrases".into());
    }
    let module = build_marker_module(&phrases);
    let mut after = format!("{module}\n{before}");
    after = ensure_pin_call(&after);
    let sha_before = sha256_str(&before);
    let sha_after = sha256_str(&after);
    fs::write(&entry, &after).map_err(|e| e.to_string())?;
    manifest.files.push(FileRecord {
        path: entry
            .strip_prefix(crate_dir)
            .unwrap_or(&entry)
            .to_string_lossy()
            .replace('\\', "/"),
        sha256_before: sha_before,
        sha256_after: sha_after,
        injections: vec![InjectionRecord {
            kind: InjectionKind::RustSrc,
            phrases: phrases.iter().map(|(_, p)| p.clone()).collect(),
        }],
    });

    let cargo = crate_dir.join("Cargo.toml");
    if cargo.exists() {
        let c_before = fs::read_to_string(&cargo).map_err(|e| e.to_string())?;
        let c_after = patch_cargo_toml(&c_before);
        if c_after != c_before {
            let sb = sha256_str(&c_before);
            let sa = sha256_str(&c_after);
            fs::write(&cargo, &c_after).map_err(|e| e.to_string())?;
            manifest.files.push(FileRecord {
                path: "Cargo.toml".into(),
                sha256_before: sb,
                sha256_after: sa,
                injections: vec![InjectionRecord {
                    kind: InjectionKind::RustSrc,
                    phrases: vec!["features.revguard_markers".into()],
                }],
            });
        }
    }
    Ok(manifest)
}

/// Remove injected Rust source markers and optional features block.
pub fn strip_rust_src(crate_dir: &Path) -> Result<(usize, Vec<(String, String, String)>), String> {
    // returns (stripped_count, hash_checks: path, expected_before, got)
    let entry = find_entry(crate_dir)?;
    let mut stripped = 0;
    let mut checks = Vec::new();

    let content = fs::read_to_string(&entry).map_err(|e| e.to_string())?;
    if content.contains(RUST_MARKER_START) {
        let cleaned = strip_pin_call(&strip_rust_file(&content));
        let cleaned = ensure_trailing_nl(&cleaned);
        fs::write(&entry, &cleaned).map_err(|e| e.to_string())?;
        stripped += 1;
        checks.push((
            entry
                .strip_prefix(crate_dir)
                .unwrap_or(&entry)
                .to_string_lossy()
                .into(),
            String::new(),
            sha256_str(&cleaned),
        ));
    }

    let cargo = crate_dir.join("Cargo.toml");
    if cargo.exists() {
        let c = fs::read_to_string(&cargo).map_err(|e| e.to_string())?;
        if c.contains("revguard_markers") {
            let nc = strip_cargo_features(&c);
            fs::write(&cargo, &nc).map_err(|e| e.to_string())?;
            stripped += 1;
        }
    }
    Ok((stripped, checks))
}

fn ensure_trailing_nl(s: &str) -> String {
    let mut o = s.to_string();
    if !o.ends_with('\n') {
        o.push('\n');
    }
    o
}

fn strip_rust_file(content: &str) -> String {
    if let Some(start) = content.find(RUST_MARKER_START) {
        if let Some(end_rel) = content[start..].find(RUST_MARKER_END) {
            let end = start + end_rel + RUST_MARKER_END.len();
            // consume following newline
            let mut end2 = end;
            if content[end2..].starts_with('\n') {
                end2 += 1;
            }
            // also a blank line we inserted
            if content[end2..].starts_with('\n') {
                end2 += 1;
            }
            return format!("{}{}", &content[..start], &content[end2..]);
        }
    }
    content.to_string()
}

fn strip_pin_call(content: &str) -> String {
    let lines: Vec<&str> = content.lines().collect();
    let mut out: Vec<&str> = Vec::new();
    let mut i = 0;
    while i < lines.len() {
        let t = lines[i].trim();
        if t == "#[cfg(feature = \"revguard_markers\")]"
            && i + 1 < lines.len()
            && lines[i + 1].contains("__revguard_pin_markers()")
        {
            i += 2;
            continue;
        }
        if t.contains("__revguard_pin_markers()") {
            i += 1;
            continue;
        }
        out.push(lines[i]);
        i += 1;
    }
    out.join("\n")
}

pub fn is_rust_injected(content: &str) -> bool {
    content.contains(RUST_MARKER_START)
}
